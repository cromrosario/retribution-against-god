#!/usr/bin/env python3
"""「会心」の表記をすべて「クリティカルヒット」に統一する(ゲーム内の文字のみ)。
 ・ログ: 会心の一撃! → クリティカルヒット!   ・「必ず会心」→「必ずクリティカルヒット」
 ・能力系: 会心範囲+N → クリティカルヒット率+(5xN)%(d20で1広がる=5%)、会心↑ → クリティカル率↑ / クリティカルヒット率上昇
使い方: python3 tools/apply_crit_text.py game/index.html [--remove]
 **他の apply_*.py を全部適用したあと、最後に実行する**。他のスクリプトの文言を変えたら tools/make_crit_text.py で作り直す。
 すでに置換済みの箇所は飛ばす。--remove で元にバイト一致。"""
import sys
path = sys.argv[1]; remove = "--remove" in sys.argv
s = open(path, encoding="utf-8", newline="").read()
PAIRS = [
    ("19・20で会心",
     "19・20でクリティカルヒット"),
    ("[\"会心\", \"crit\"",
     "[\"クリティカル\", \"crit\""),
    ("n: \"会心↑\"",
     "n: \"クリティカル率↑\""),
    ("必中会心",
     "必中クリティカル"),
    ("20%・会心↑\", {",
     "20%・クリティカルヒット率上昇\", {"),
    ("6, desc: \"必ず会心。必中 3d10+4",
     "6, desc: \"必ずクリティカルヒット。必中 3d10+4"),
    ("撃を必ず会心にす",
     "撃を必ずクリティカルヒットにす"),
    (" \"必ず会心にな",
     " \"必ずクリティカルヒットにな"),
    ("会心↑。次の攻撃が必ず会心",
     "クリティカルヒット率上昇。次の攻撃が必ずクリティカルヒット"),
    ("ルが必ず会心\",",
     "ルが必ずクリティカルヒット\","),
    ("間、会心↑。必",
     "間、クリティカルヒット率上昇。必"),
    ("間、会心↑・与",
     "間、クリティカルヒット率上昇・与"),
    ("。次の攻撃が必ず会心\", { d",
     "。次の攻撃が必ずクリティカルヒット\", { d"),
    ("25%・会心↑\", {",
     "25%・クリティカルヒット率上昇\", {"),
    ("会心の範囲が1広がる",
     "クリティカルヒット率+5%"),
    ("会心と追撃",
     "クリティカルヒットと追撃"),
    ("(\"必ず会心\")",
     "(\"必ずクリティカルヒット\")"),
    ("\"会心範囲+\" + v",
     "\"クリティカルヒット率+\" + (5 * v) + \"%\""),
    ("会心が出なくなる",
     "クリティカルヒットが出なくなる"),
    ("会心(crit)",
     "クリティカルヒット(crit)"),
    ("\", desc: \"必ず会心。必中 3d10+3",
     "\", desc: \"必ずクリティカルヒット。必中 3d10+3"),
    ("会心の範囲も広がる",
     "クリティカル率も上がる"),
    ("狙いすました会心の一撃！\" : \"会心の一撃！",
     "狙いすましたクリティカルヒット！\" : \"クリティカルヒット！"),
    ("(\"会心！\",",
     "(\"クリティカルヒット！\","),
    ("会心の出目",
     "クリティカルの出目"),
    ("kv(\"会心\"",
     "kv(\"クリティカルヒット\"")
]
n_done = 0
for old, new in (reversed(PAIRS) if remove else PAIRS):
    src, dst = (new, old) if remove else (old, new)
    if s.count(src) == 1:
        s = s.replace(src, dst); n_done += 1
    elif s.count(dst) == 1:
        pass  # すでに済み
    else:
        raise SystemExit("接続箇所が見つからない/重複: " + src[:40])
open(path, "w", encoding="utf-8", newline="").write(s)
print(("removed " if remove else "applied ") + str(n_done) + " / " + str(len(PAIRS)))
